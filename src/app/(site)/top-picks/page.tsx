import type { Metadata } from "next";
import Link from "next/link";
import { and, asc, eq } from "drizzle-orm";
import { Sparkles } from "lucide-react";
import { db } from "@/db";
import { picks as picksTable, slates } from "@/db/schema";
import type { Pick } from "@/db/schema";
import { getAuth } from "@/lib/auth";
import { PickCard } from "@/components/pick-card";
import { Reveal } from "@/components/ui/motion";
import { slateDateString } from "@/lib/slate-date";
import { formatSlateDate } from "@/lib/i18n/format";
import { cn } from "@/lib/utils";

export const metadata: Metadata = {
  title: "Our Top Picks",
  description: "The day's top 15 MLB and NFL picks from our proprietary SSA framework.",
};

// Per-request: today's slate can change (or publish) between requests.
export const dynamic = "force-dynamic";

const SPORT_TABS = [
  { key: "mlb", label: "MLB", sport: "baseball" as const, league: "MLB" },
  { key: "nfl", label: "NFL", sport: "football" as const, league: "NFL" },
];

export default async function TopPicksPage({
  searchParams,
}: {
  searchParams: Promise<{ sport?: string }>;
}) {
  const [auth, params] = await Promise.all([getAuth(), searchParams]);

  const date = slateDateString();
  const active = SPORT_TABS.find((s) => s.key === params.sport) ?? SPORT_TABS[0];

  const [slate] = await db.select().from(slates).where(eq(slates.date, date)).limit(1);

  // Admins preview drafts; nobody else sees an unpublished slate exists.
  const visible = Boolean(slate?.publishedAt) || Boolean(auth?.isAdmin);

  const rows: Pick[] = visible
    ? await db
        .select()
        .from(picksTable)
        .where(
          and(
            eq(picksTable.slateDate, date),
            eq(picksTable.sport, active.sport),
            eq(picksTable.league, active.league),
          ),
        )
        .orderBy(asc(picksTable.rank))
        .limit(15)
    : [];

  return (
    <div className="mx-auto max-w-5xl px-4 py-10 sm:px-6">
      {/* -------------------------------------------------------------- head */}
      <div className="flex items-center gap-2 text-[0.6875rem] font-semibold uppercase tracking-[0.2em] text-brand">
        <Sparkles className="size-3.5" aria-hidden="true" />
        Our top picks
      </div>
      <h1 className="mt-2 text-2xl font-semibold tracking-tight sm:text-3xl">
        Today&apos;s top 15, MLB &amp; NFL
      </h1>
      <p className="mt-3 max-w-2xl text-sm leading-relaxed text-fg-muted">
        Generated by our proprietary SSA framework. You&apos;re first through the door — this
        is our beta, and you&apos;re running it with us. Let&apos;s beat the books.
      </p>

      {/* -------------------------------------------------------------- tabs */}
      <nav
        aria-label="Sport"
        className="mt-8 -mb-px flex items-center gap-1 border-b border-border"
      >
        {SPORT_TABS.map((tab) => {
          const isActive = tab.key === active.key;
          return (
            <Link
              key={tab.key}
              href={`/top-picks?sport=${tab.key}`}
              aria-current={isActive ? "page" : undefined}
              className={cn(
                "relative inline-flex px-3 py-2.5 text-sm font-medium transition-colors",
                isActive ? "text-brand" : "text-fg-muted hover:text-fg",
              )}
            >
              {tab.label}
              {isActive && (
                <span className="absolute inset-x-3 -bottom-px h-0.5 rounded-full bg-brand" />
              )}
            </Link>
          );
        })}
      </nav>

      {/* ------------------------------------------------------------- board */}
      {rows.length === 0 ? (
        <div className="card-hairline mt-8 p-10 text-center">
          <h2 className="text-lg font-semibold tracking-tight">
            {visible ? `No ${active.label} picks today` : "The board isn't up yet"}
          </h2>
          <p className="mx-auto mt-2 max-w-sm text-sm text-fg-muted">
            {visible
              ? "Check back shortly, or flip to the other sport."
              : "Picks go out before the first kick-off. Check back shortly."}
          </p>
        </div>
      ) : (
        <>
          <p className="mt-6 text-xs text-fg-subtle">
            <span className="num">{formatSlateDate(date)}</span> · {rows.length} of today&apos;s
            top {active.label} picks
          </p>
          <div className="mt-4 grid gap-3 sm:grid-cols-2">
            {rows.map((p, i) => (
              <Reveal key={p.id} delay={Math.min(i * 0.02, 0.2)}>
                <PickCard pick={p} />
              </Reveal>
            ))}
          </div>
        </>
      )}
    </div>
  );
}
